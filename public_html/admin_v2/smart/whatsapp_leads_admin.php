$configTxt = __DIR__ . '/whatsapp_leads_config.txt';

$numbers = [];
$current = null;
$message = null;
$labels = [];

function sanitize_number($n) {
    if ($n === 'AUTO') return 'AUTO';
    return preg_replace('/\D+/', '', (string)$n);
}

function get_label($n, $labels) {
    $n = sanitize_number($n);
    if (isset($labels[$n]) && $labels[$n] !== '') {
        return $labels[$n];
    }
    return null; 
}

// Load numbers and current from config 
if (file_exists($configPhp)) {
    include $configPhp; // expects $whatsappNumberList and $whatsappNumber
    if (isset($whatsappNumberList) && is_array($whatsappNumberList)) {
        $numbers = array_values(array_unique(array_map('sanitize_number', $whatsappNumberList)));
    }
    if (isset($whatsappNumber)) {
        $current = sanitize_number($whatsappNumber);
    }
    if (isset($whatsappNumberLabels) && is_array($whatsappNumberLabels)) {
        // Normalize labels keys to digit-only numbers
        foreach ($whatsappNumberLabels as $k => $v) {
            $labels[sanitize_number($k)] = trim((string)$v);
        }
    }
} elseif (file_exists($configTxt)) {
    $lines = file($configTxt, FILE_IGNORE_NEW_LINES | FILE_SKIP_EMPTY_LINES);
    $lines = array_map('trim', $lines);
    $lines = array_filter($lines, function ($l) { return $l !== ''; });
    if (!empty($lines)) {
        $current = sanitize_number($lines[0]);
        $numbers = array_values(array_unique(array_map('sanitize_number', $lines)));
    }
}

// Handle selection update
if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    $selected = isset($_POST['number']) ? sanitize_number($_POST['number']) : '';
    if ($selected === '') {
        $message = 'Please select a number.';
    } else {
        if (file_exists($configPhp)) {
            $content = file_get_contents($configPhp);
            $updated = preg_replace('/\$whatsappNumber\s*=\s*["\']([^"\']*)["\'];/', '$whatsappNumber = "' . $selected . '";', $content, -1, $count);
            if ($count === 0) {
                $updated .= PHP_EOL . '$whatsappNumber = "' . $selected . '";' . PHP_EOL;
            }
            file_put_contents($configPhp, $updated);
            $current = $selected;
            // Refresh numbers from PHP config to maintain consistency
            include $configPhp;
            if (isset($whatsappNumberList) && is_array($whatsappNumberList)) {
                $numbers = array_values(array_unique(array_map('sanitize_number', $whatsappNumberList)));
            }
            $message = 'Active WhatsApp number updated.';
        } elseif (file_exists($configTxt)) {
            // Ensure selected is included and becomes the first line
            if (!in_array($selected, $numbers, true)) {
                $numbers[] = $selected;
            }
            $linesOut = array_merge([$selected], array_values(array_filter($numbers, fn($n) => $n !== $selected)));
            file_put_contents($configTxt, implode(PHP_EOL, $linesOut) . PHP_EOL);
            $current = $selected;
            $message = 'Active WhatsApp number updated.';
        } else {
            // No config exists; create PHP config by default
            $phpContent = "<?php\n// Auto-generated by whatsapp_leads_admin.php\n$whatsappNumberList = [\n    \"$selected\"\n];\n$whatsappNumber = \"$selected\";\n";
            file_put_contents($configPhp, $phpContent);
            $numbers = [$selected];
            $current = $selected;
            $message = 'Config file created and active number set.';
        }
    }
}
